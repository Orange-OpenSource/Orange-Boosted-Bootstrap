#!/usr/bin/env node

// generate-icons.mjs
//
// Generates the typed icon data of @ouds/icons (src/icons/<name>.ts and src/index.ts) from the
// OUDS Web icon sprites (one `ouds-web-sprite.svg` per brand). The icons to generate are listed in
// icons.config.json.
//
// Usage (from the repository root):
//   npx nx run @ouds/icons:generate-icons          write the files
//   node libs/icons/scripts/generate-icons.mjs --check   exit 1 when the committed files are out of date
//
// An icon can only use <path> elements (with `d`, `fill`, and `fill-rule`), because that is what
// the framework components render. Any other element in a listed symbol makes the script fail.

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const PACKAGE_DIRECTORY = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '..',
);

const HEADER =
    '// Generated by libs/icons/scripts/generate-icons.mjs from the OUDS Web icon sprites. Do not edit by hand.\n// Run `npx nx run @ouds/icons:generate-icons` to update it.\n';

const parseAttributes = (source) => {
    const attributes = {};

    for (const [, name, value] of source.matchAll(
        /([\w:-]+)\s*=\s*"([^"]*)"/g,
    )) {
        attributes[name] = value;
    }

    return attributes;
};

/**
 * Reads the requested symbols of a sprite.
 *
 * @param {string} sprite Content of the SVG sprite.
 * @param {string[]} names Ids of the symbols to read.
 * @returns {Map<string, {viewBox: string, paths: {d: string, fill?: string, fillRule?: string}[]}>}
 */
export const parseSprite = (sprite, names) => {
    const symbols = new Map();

    for (const [, rawAttributes, body] of sprite.matchAll(
        /<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g,
    )) {
        const attributes = parseAttributes(rawAttributes);

        if (!names.includes(attributes.id)) {
            continue;
        }

        if (!attributes.viewBox) {
            throw new Error(`Symbol "${attributes.id}" has no viewBox`);
        }

        const paths = [];

        for (const [, tag, rawPathAttributes] of body.matchAll(
            /<([a-zA-Z][\w-]*)\b([^>]*?)\/?>/g,
        )) {
            if (tag !== 'path') {
                throw new Error(
                    `Symbol "${attributes.id}" contains a <${tag}> element: only <path> is supported`,
                );
            }

            const {
                d,
                fill,
                'fill-rule': fillRule,
            } = parseAttributes(rawPathAttributes);

            if (!d) {
                throw new Error(
                    `Symbol "${attributes.id}" has a <path> without a "d" attribute`,
                );
            }

            paths.push({
                d,
                ...(fill && { fill }),
                ...(fillRule && { fillRule }),
            });
        }

        if (paths.length === 0) {
            throw new Error(`Symbol "${attributes.id}" has no <path>`);
        }

        symbols.set(attributes.id, { viewBox: attributes.viewBox, paths });
    }

    for (const name of names) {
        if (!symbols.has(name)) {
            throw new Error(`Symbol "${name}" not found in the sprite`);
        }
    }

    return symbols;
};

/** `functional-status-warning` becomes `functionalStatusWarning`. */
export const toExportName = (name) => {
    const camelCase = name.replace(/-([a-z\d])/g, (_, character) =>
        character.toUpperCase(),
    );

    return /^\d/.test(camelCase)
        ? `icon${camelCase.charAt(0).toUpperCase()}${camelCase.slice(1)}`
        : camelCase;
};

const quote = (value) =>
    `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

const pathToSource = ({ d, fill, fillRule }) => {
    const properties = [`d: ${quote(d)}`];

    if (fill) {
        properties.push(`fill: ${quote(fill)}`);
    }

    if (fillRule) {
        properties.push(`fillRule: ${quote(fillRule)}`);
    }

    return `{ ${properties.join(', ')} }`;
};

/**
 * Builds the source of the data file of one icon.
 *
 * @param {string} name Id of the icon.
 * @param {string} viewBox
 * @param {Record<string, {d: string, fill?: string, fillRule?: string}[]>} pathsByBrand
 */
export const iconToSource = (name, viewBox, pathsByBrand) => {
    const brands = Object.entries(pathsByBrand)
        .map(
            ([brand, paths]) =>
                `${quote(brand)}: [${paths.map(pathToSource).join(', ')}]`,
        )
        .join(', ');

    return `${HEADER}import type { OudsIcon } from '@ouds/core';

export const ${toExportName(name)}: OudsIcon = {
  name: ${quote(name)},
  viewBox: ${quote(viewBox)},
  brands: { ${brands} },
};
`;
};

const indexToSource = (names) =>
    `${HEADER}${names.map((name) => `export { ${toExportName(name)} } from './icons/${name}';`).join('\n')}\n`;

const format = async (source, filePath) => {
    const options = await prettier.resolveConfig(filePath);

    return prettier.format(source, { ...options, filepath: filePath });
};

/**
 * Returns the content of every generated file, keyed by its path relative to the package.
 *
 * @param {{ packageDirectory?: string }} [options]
 * @returns {Promise<Map<string, string>>}
 */
export const generate = async ({
    packageDirectory = PACKAGE_DIRECTORY,
} = {}) => {
    const config = JSON.parse(
        await fs.readFile(
            path.join(packageDirectory, 'icons.config.json'),
            'utf8',
        ),
    );
    const spriteByBrand = {};

    for (const brand of config.brands) {
        const spritePath = path.resolve(
            packageDirectory,
            config.sprite.replace('{brand}', brand),
        );

        spriteByBrand[brand] = parseSprite(
            await fs.readFile(spritePath, 'utf8'),
            config.icons,
        );
    }

    const files = new Map();
    const [referenceBrand] = config.brands;

    for (const name of config.icons) {
        const { viewBox } = spriteByBrand[referenceBrand].get(name);
        const pathsByBrand = {};

        for (const brand of config.brands) {
            const symbol = spriteByBrand[brand].get(name);

            if (symbol.viewBox !== viewBox) {
                throw new Error(
                    `Symbol "${name}" has a different viewBox in the ${brand} sprite`,
                );
            }

            // Brands that share the drawing of the first brand (Orange Compact reuses Orange) are not
            // stored; `getIconPaths` of @ouds/core falls back to it.
            const reference = pathsByBrand[referenceBrand];

            if (
                brand === referenceBrand ||
                JSON.stringify(symbol.paths) !== JSON.stringify(reference)
            ) {
                pathsByBrand[brand] = symbol.paths;
            }
        }

        const relativePath = `src/icons/${name}.ts`;

        files.set(
            relativePath,
            await format(
                iconToSource(name, viewBox, pathsByBrand),
                path.join(packageDirectory, relativePath),
            ),
        );
    }

    files.set(
        'src/index.ts',
        await format(
            indexToSource(config.icons),
            path.join(packageDirectory, 'src/index.ts'),
        ),
    );

    return files;
};

const main = async () => {
    const check = process.argv.includes('--check');
    const files = await generate();
    let outdated = false;

    for (const [relativePath, content] of files) {
        const filePath = path.join(PACKAGE_DIRECTORY, relativePath);
        const current = await fs.readFile(filePath, 'utf8').catch(() => null);

        if (check) {
            if (current !== content) {
                outdated = true;
                console.error(`${relativePath} is out of date`);
            }
        } else if (current !== content) {
            await fs.mkdir(path.dirname(filePath), { recursive: true });
            await fs.writeFile(filePath, content);
            console.log(`Wrote ${relativePath}`);
        }
    }

    if (outdated) {
        console.error(
            'Run `npx nx run @ouds/icons:generate-icons` and commit the result.',
        );
        process.exit(1);
    }
};

if (
    process.argv[1] &&
    path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
    await main();
}
